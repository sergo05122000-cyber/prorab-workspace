#!/usr/bin/env bash
# Стоп перед ПЛАТНОЙ видеогенерацией (Kling / Higgsfield / Loore render), по образцу video-gate BASEMIND (24.10).
#   video_gate.sh <папка-проекта> <команда генерации ...>
# Запускает команду, только если в папке есть непустой СОГЛАСОВАНО.txt: утверждённые Сергеем кадры
# и его «ок» на трату (дата, сумма/кредиты). Порядок: кадры картинками → «ок» по каждому → 2 пробы дешёвой моделью → полный прогон.
set -u
P="${1:-}"; shift 2>/dev/null || true
[ -z "$P" ] || [ $# -eq 0 ] && { echo "нужно: video_gate.sh <папка-проекта> <команда ...>" >&2; exit 2; }
S="$P/СОГЛАСОВАНО.txt"
if [ ! -s "$S" ]; then
  echo "ОСТАНОВЛЕНО: нет $S. Без утверждённых кадров и «ок» Сергея на трату видео не генерим." >&2; exit 1
fi
echo "согласовано:"; sed 's/^/  · /' "$S"
echo "$(date '+%F %T') $*" >> "$P/gen_spend.log"
exec "$@"
